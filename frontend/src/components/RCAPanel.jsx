import { useState } from 'react';
import { api } from '../api/client';

const evidenceLabels = {
  awaiting_feedback: 'Awaiting division feedback',
  insufficient_evidence: 'Insufficient evidence',
  feedback_available: 'Division feedback available',
  ai_draft: 'AI draft · engineer review required',
};

export default function RCAPanel({domainId, selectedCell, rcaData, loading, error, onTriggerRCA, onClose, onViewHistory, onFeedbackSaved}) {
  const [explanation, setExplanation] = useState('');
  const [action, setAction] = useState('');
  const [saving, setSaving] = useState(false);
  const [feedbackError, setFeedbackError] = useState('');
  const save = async (e) => {
    e.preventDefault(); setSaving(true); setFeedbackError('');
    try {
      await api.addFeedback(domainId, {fact_id: selectedCell.fact_id, explanation, corrective_action: action});
      setExplanation(''); setAction(''); onFeedbackSaved();
    } catch (err) { setFeedbackError(err.message); }
    finally { setSaving(false); }
  };
  return <aside className="investigation-panel glass border border-white/10 overflow-hidden">
    <header className="p-4 border-b border-white/10 flex justify-between items-start gap-3">
      <div><p className="text-xs text-indigo-300 uppercase tracking-wider">Performance investigation</p><h2 className="font-semibold mt-1">{selectedCell.kpi_name}</h2>
        <p className="text-xs text-slate-400 mt-1">{selectedCell.location_name} · {selectedCell.date}</p></div>
      <button className="btn-ghost icon-button" aria-label="Close investigation" onClick={onClose}><svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" aria-hidden="true"><path d="m6 6 12 12M18 6 6 18" /></svg></button>
    </header>
    <div className="p-4 space-y-4 text-sm">
      <div className="grid grid-cols-2 gap-3">
        <div className="glass-sm p-3"><span className="text-xs text-slate-400 block">Actual</span><strong>{selectedCell.actual_value} {selectedCell.unit}</strong></div>
        <div className="glass-sm p-3"><span className="text-xs text-slate-400 block">Target / limit</span><strong>{selectedCell.target_value ?? 'Not supplied'} {selectedCell.unit}</strong></div>
      </div>
      <div className="flex flex-wrap gap-2 text-xs">
        <span className={selectedCell.status === 'RED' ? 'text-red-300' : selectedCell.status === 'YELLOW' ? 'text-yellow-300' : 'text-emerald-300'}>{selectedCell.status === 'RED' ? 'Missing target' : selectedCell.status === 'GREEN' ? 'Meeting target' : 'Target unavailable'}</span>
        {selectedCell.attainment_pct != null && <span className="text-slate-400">· {selectedCell.attainment_pct}% attainment</span>}
      </div>
      <p className="text-xs text-slate-400">{selectedCell.higher_is_better ? 'Higher' : 'Lower'} is better.
        {selectedCell.z_score != null ? ' Historical Z: '+selectedCell.z_score.toFixed(2)+'.' : ' Insufficient or constant history for a Z-score.'}</p>
      {selectedCell.source_file && <div className="glass-sm p-3 text-xs text-slate-400 break-words">
        <p className="font-semibold text-slate-200">{selectedCell.division}</p>
        <p className="mt-1">{selectedCell.source_file} · source row {selectedCell.source_row}</p>
      </div>}
      <div className="investigation-actions">
        <button className="btn-ghost flex-1 text-xs" onClick={onViewHistory}>View recent history</button>
        <button className="btn-primary flex-1 text-xs" disabled={loading} onClick={() => onTriggerRCA(selectedCell)}>Review / draft RCA</button>
      </div>
      {loading && <p role="status" className="notice-info">Reviewing feedback for this exact reading…</p>}
      {error && <p role="alert" className="notice-error">{error}</p>}
      {rcaData && <>
        <div className="notice-info">
          <p className="font-semibold">{evidenceLabels[rcaData.evidence_status] || rcaData.evidence_status}</p>
          <p className="text-sm mt-2">{rcaData.evidence_status === 'ai_draft' ? `Generated by AI · ${rcaData.llm_model}` : rcaData.evidence_status === 'feedback_available' ? 'AI was not used for this output. Showing an attributed feedback summary.' : rcaData.evidence_status === 'awaiting_feedback' ? 'No AI call: this reading has no division feedback.' : `Model response · ${rcaData.llm_model}. The supplied evidence does not support a cause.`}</p>
          <p className="text-xs mt-2">References identify the submitted feedback. They do not independently prove that the reported cause is correct.</p>
        </div>
        <section className="glass-sm p-3"><h3 className="text-xs uppercase text-indigo-300 mb-2">Reported cause / RCA draft</h3><p className="leading-relaxed whitespace-pre-wrap">{rcaData.root_cause}</p></section>
        <section className="glass-sm p-3"><h3 className="text-xs uppercase text-emerald-300 mb-2">Corrective action / next check</h3><p className="leading-relaxed whitespace-pre-wrap">{rcaData.prescriptive_action}</p></section>
        {rcaData.evidence.map(e => <details key={e.feedback_id} className="glass-sm p-3" open>
          <summary className="cursor-pointer text-xs text-indigo-300">[F{e.feedback_id}] {e.division} feedback</summary>
          <p className="mt-2 text-xs whitespace-pre-wrap">{e.explanation}</p>
          {e.corrective_action && <p className="mt-2 text-xs text-emerald-200">Proposed action: {e.corrective_action}</p>}
        </details>)}
        <p className="text-[11px] text-slate-500 break-words">{rcaData.llm_model}</p>
      </>}
      {selectedCell.division && <form onSubmit={save} className="border-t border-white/10 pt-4 space-y-3">
        <h3 className="font-semibold">Record division feedback</h3>
        <p className="text-xs text-slate-400">For {selectedCell.division}, this KPI and {selectedCell.date}. This demo does not authenticate a division representative.</p>
        <label className="field-label">Explanation and supporting observations
          <textarea className="field-input" rows={3} required minLength={5} maxLength={4000} value={explanation} onChange={e => setExplanation(e.target.value)} />
        </label>
        <label className="field-label">Proposed corrective action
          <textarea className="field-input" rows={2} maxLength={4000} value={action} onChange={e => setAction(e.target.value)} />
        </label>
        {feedbackError && <p role="alert" className="notice-error">{feedbackError}</p>}
        <button className="btn-primary w-full text-xs" disabled={saving || loading}>{saving ? 'Saving…' : 'Save feedback and draft RCA'}</button>
        <p className="text-[11px] text-slate-500">AI drafts use the selected reading and its division feedback. The draft must reference that feedback and remains subject to analyst review.</p>
      </form>}
      <p className="text-xs text-slate-500 border-t border-white/10 pt-3">Advisory only. Network engineers review explanations and actions; OmniKPI does not execute network changes.</p>
    </div>
  </aside>;
}
