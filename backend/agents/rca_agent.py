"""
agents/rca_agent.py — Root Cause Analysis Agent (RCA Agent).

Architecture (from ANTIGRAVITY_PROJECT_CONTEXT.md):
    - LLM narrates root cause from data retrieved via FTS5 shift log search
    - Confidence score is derived from Z-score magnitude — NOT generated by the LLM
    - AI is advisory only: human-in-the-loop, read-only (Purdue Model / ISA-95)
    - LLM accessed via OpenRouter/NineRouter (OpenAI-compatible SDK, just swap base_url)

Flow:
    1. Load anomaly data from fact_kpi (latest period)
    2. Retrieve corroborating shift logs via SQLite FTS5 (domain + location filtered)
    3. Compute deterministic confidence score from Z-score + log corroboration count
    4. Call LLM with structured context, instruct JSON output
    5. Parse LLM response; graceful fallback if LLM is unavailable (rate limit etc.)
    6. Attach deterministic confidence before returning — LLM never touches this number

Model selection (for ITASE "alasan pemilihan teknologi" criterion):
    - meta-llama/llama-3.1-70b-instruct via OpenRouter free tier
    - 128k context window: sufficient for multi-entry shift log retrieval
    - Strong instruction-following for structured JSON output format
    - Low latency for interactive RCA queries
    - Fallback: swap LLM_MODEL env var to gpt-4o / claude-3-5-sonnet for CALIBER Final Stage
"""

import json
import math
import os

from openai import AsyncOpenAI
from sqlalchemy import func, text
from sqlalchemy.orm import Session

from database import DimKPI, DimLocation, DimPeriod, FactKPI

# ─── LLM Client ───────────────────────────────────────────────────────────────
# OpenAI SDK compatible — swap base_url to change provider

OPENROUTER_BASE_URL = os.getenv("OPENROUTER_BASE_URL", "https://openrouter.ai/api/v1")
OPENROUTER_API_KEY  = os.getenv("OPENROUTER_API_KEY", "")
LLM_MODEL           = os.getenv("LLM_MODEL", "meta-llama/llama-3.1-70b-instruct")

_client = AsyncOpenAI(
    api_key=OPENROUTER_API_KEY or "no-key-set",
    base_url=OPENROUTER_BASE_URL,
)


# ─── Confidence Score (deterministic, not LLM-generated) ─────────────────────

def compute_confidence(z_score: float, log_count: int) -> int:
    """
    Map Z-score magnitude + shift log corroboration to a confidence score (0-98).
    This value is computed deterministically — the LLM is never asked to produce it.

    Formula:
        z_component  = min(88, 40 + |Z| * 2.0)   # caps at 88%
        log_bonus    = min(10, log_count * 4)      # up to +10% for corroborating logs
        confidence   = min(98, z_component + log_bonus)
    """
    abs_z = abs(z_score)
    z_component = min(88, int(40 + abs_z * 2.0))
    log_bonus   = min(10, log_count * 4)
    return min(98, z_component + log_bonus)


def build_confidence_basis(z_score: float, log_count: int, window_days: int = 30) -> str:
    basis = f"Z-score {z_score:.2f} ({window_days}-day historical window, n={window_days})"
    if log_count > 0:
        basis += f" + {log_count} corroborating shift log{'s' if log_count > 1 else ''} retrieved via FTS5"
    return basis


# ─── Shift Log Retrieval (FTS5) ───────────────────────────────────────────────

def retrieve_shift_logs(
    db: Session,
    domain_id: int,
    location_id: int,
    kpi_name: str,
) -> list[dict]:
    """
    Retrieve operationally relevant shift logs using SQLite FTS5 full-text search.
    Filters by domain_id and location_id (stored as UNINDEXED columns in FTS5 table).

    Query construction:
        - Extract meaningful terms from kpi_name (skip short/generic words)
        - Join terms with OR for broader recall
        - Limit to 5 most relevant results (FTS5 rank ordering)

    Falls back to empty list on any FTS5 error (e.g., weird KPI name with special chars).
    """
    stop_words = {"rate", "time", "ratio", "index", "percentage", "loss", "mean"}
    raw_terms = [
        w.lower() for w in kpi_name.split()
        if len(w) >= 4 and w.lower() not in stop_words
    ]

    # Guarantee at least one search term
    if not raw_terms:
        raw_terms = [kpi_name.split()[0].lower()]

    fts_query = " OR ".join(raw_terms)

    try:
        rows = db.execute(
            text("""
                SELECT log_id, log_text
                FROM shift_logs_fts
                WHERE shift_logs_fts MATCH :query
                  AND domain_id   = :domain_id
                  AND location_id = :location_id
                ORDER BY rank
                LIMIT 5
            """),
            {
                "query":       fts_query,
                "domain_id":   domain_id,
                "location_id": location_id,
            },
        ).fetchall()
        return [{"log_id": r[0], "log_text": r[1]} for r in rows]
    except Exception:
        return []


# ─── LLM Prompt Builder ───────────────────────────────────────────────────────

def _build_prompt(
    domain_name: str,
    kpi: DimKPI,
    loc: DimLocation,
    fact: FactKPI,
    latest_date: str,
    logs: list[dict],
) -> tuple[str, str]:
    """Build system + user messages for the RCA LLM call."""

    deviation_pct = 0.0
    if fact.target_value and fact.target_value != 0:
        deviation_pct = abs(
            (fact.actual_value - fact.target_value) / fact.target_value * 100
        )

    context = {
        "kpi": {
            "name":            kpi.kpi_name,
            "archetype":       kpi.kpi_archetype,
            "unit":            kpi.unit,
            "target":          kpi.target_threshold,
            "higher_is_better": kpi.higher_is_better,
            "formula":         kpi.formula_description,
        },
        "location": {
            "name": loc.location_name,
            "type": loc.location_type,
        },
        "anomaly": {
            "actual_value":             fact.actual_value,
            "target_value":             fact.target_value,
            "deviation_from_target_pct": round(deviation_pct, 1),
            "z_score":                  round(fact.z_score or 0, 2),
            "date":                     latest_date,
        },
        "shift_logs": [{"log_text": lg["log_text"]} for lg in logs],
    }

    system_prompt = f"""You are an expert Root Cause Analysis (RCA) engineer for {domain_name} operations.
Analyze the provided KPI anomaly data and operational shift logs, then produce a concise, actionable root cause analysis.

STRICT RULES:
- Ground your analysis ONLY in the provided shift log evidence. Do not invent events not in the logs.
- Do NOT mention, estimate, or generate any confidence score — confidence is computed separately.
- root_cause: 1-2 sentences, technical and specific.
- prescriptive_action: 2-3 sentences, concrete next steps for the operations team.
- estimated_impact: 1 sentence, referencing the severity scale of the anomaly.
- If shift_logs is empty, base analysis on the KPI deviation pattern alone.

Respond with ONLY valid JSON — no prose, no markdown, no explanation outside the JSON:
{{
  "root_cause": "...",
  "prescriptive_action": "...",
  "estimated_impact": "..."
}}"""

    user_message = (
        f"Analyze this KPI anomaly and provide root cause analysis:\n\n"
        f"{json.dumps(context, indent=2, ensure_ascii=False)}"
    )

    return system_prompt, user_message


# ─── Fallback Analysis (no LLM) ───────────────────────────────────────────────

def _fallback_analysis(kpi: DimKPI, loc: DimLocation, fact: FactKPI, logs: list[dict]) -> dict:
    """
    Deterministic fallback when LLM is unavailable (rate limit, network error, etc.).
    Uses shift log text directly without LLM narration.
    Critical for demo resilience — CALIBER Final Stage may hit free-tier rate limits.
    """
    if logs:
        log_excerpt = logs[0]["log_text"][:200]
        root_cause = (
            f"Shift log evidence at {loc.location_name}: \"{log_excerpt}...\". "
            f"Manual review of {len(logs)} retrieved log entries recommended."
        )
        prescriptive_action = (
            f"Review the {len(logs)} shift log entries for {kpi.kpi_name} "
            f"at {loc.location_name}. Escalate to the responsible operations team "
            f"for immediate inspection and corrective action."
        )
    else:
        root_cause = (
            f"Significant statistical deviation detected: {kpi.kpi_name} at "
            f"{loc.location_name} is {abs(fact.z_score or 0):.1f} standard deviations "
            f"from the 30-day mean. No shift log data available for additional context."
        )
        prescriptive_action = (
            f"Initiate manual inspection of {kpi.kpi_name} at {loc.location_name}. "
            f"Cross-check related KPIs at the same location for cascading anomalies. "
            f"Document findings in shift log for future RCA retrieval."
        )

    estimated_impact = (
        f"Anomaly magnitude (Z={fact.z_score:.2f}) indicates a significant departure "
        f"from normal operations. Immediate review is advised to prevent escalation."
    )

    return {
        "root_cause":         root_cause,
        "prescriptive_action": prescriptive_action,
        "estimated_impact":   estimated_impact,
    }


# ─── Main RCA Entry Point ─────────────────────────────────────────────────────

async def run_rca(
    db: Session,
    domain_id: int,
    kpi_id: int,
    location_id: int,
) -> dict:
    """
    Execute the full RCA pipeline for a given KPI anomaly at a given location.

    Returns a dict matching RCAResponse schema — confidence_score is deterministic,
    never from the LLM. The LLM only narrates root_cause, prescriptive_action,
    estimated_impact.

    Raises ValueError if KPI / location / fact data is not found.
    """
    # ── Load entities ─────────────────────────────────────────────────────────
    kpi = db.query(DimKPI).filter(DimKPI.kpi_id == kpi_id).first()
    loc = db.query(DimLocation).filter(DimLocation.location_id == location_id).first()

    if not kpi:
        raise ValueError(f"KPI {kpi_id} not found")
    if not loc:
        raise ValueError(f"Location {location_id} not found")

    # ── Load latest fact ──────────────────────────────────────────────────────
    latest_date: str | None = db.query(func.max(DimPeriod.date)).scalar()
    fact = (
        db.query(FactKPI)
        .join(DimPeriod, FactKPI.period_id == DimPeriod.period_id)
        .filter(
            FactKPI.kpi_id      == kpi_id,
            FactKPI.location_id == location_id,
            FactKPI.domain_id   == domain_id,
            DimPeriod.date      == latest_date,
        )
        .first()
    )
    if not fact:
        raise ValueError(
            f"No fact data for KPI {kpi_id} @ location {location_id} on {latest_date}"
        )

    # ── Retrieve shift logs (FTS5) ────────────────────────────────────────────
    logs = retrieve_shift_logs(db, domain_id, location_id, kpi.kpi_name)

    # ── Deterministic confidence (pre-LLM) ───────────────────────────────────
    confidence       = compute_confidence(fact.z_score or 0.0, len(logs))
    confidence_basis = build_confidence_basis(fact.z_score or 0.0, len(logs))

    # ── LLM narration ─────────────────────────────────────────────────────────
    domain_name = "Telecommunications" if domain_id == 1 else "Petrochemical Manufacturing"
    system_prompt, user_message = _build_prompt(
        domain_name, kpi, loc, fact, latest_date or "", logs
    )

    used_model = LLM_MODEL
    try:
        response = await _client.chat.completions.create(
            model=LLM_MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user",   "content": user_message},
            ],
            temperature=0.2,
            max_tokens=600,
        )
        raw = response.choices[0].message.content or ""

        # Extract JSON block (model may wrap in markdown code fences)
        if "```" in raw:
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]

        llm_out = json.loads(raw.strip())
        analysis = {
            "root_cause":          llm_out.get("root_cause", ""),
            "prescriptive_action": llm_out.get("prescriptive_action", ""),
            "estimated_impact":    llm_out.get("estimated_impact", ""),
        }

        # Reject empty LLM output — fall back
        if not analysis["root_cause"]:
            raise ValueError("Empty LLM output")

    except Exception as exc:
        analysis  = _fallback_analysis(kpi, loc, fact, logs)
        used_model = f"fallback ({str(exc)[:60]})"

    # ── Assemble final response ───────────────────────────────────────────────
    return {
        "kpi_name":             kpi.kpi_name,
        "location_name":        loc.location_name,
        "actual_value":         fact.actual_value,
        "z_score":              fact.z_score,
        "root_cause":           analysis["root_cause"],
        "confidence_score":     confidence,         # ← deterministic, not LLM
        "confidence_basis":     confidence_basis,   # ← shows Z-score source
        "prescriptive_action":  analysis["prescriptive_action"],
        "estimated_impact":     analysis["estimated_impact"],
        "shift_logs_retrieved": len(logs),
        "llm_model":            used_model,
    }
