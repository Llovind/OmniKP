"""
agents/rca_agent.py — Root Cause Analysis Agent (RCA Agent).

Architecture (from ANTIGRAVITY_PROJECT_CONTEXT.md):
    - LLM narrates root cause from data retrieved via FTS5 shift log search
    - Confidence score is derived from Z-score magnitude — NOT generated by the LLM
    - AI is advisory only: human-in-the-loop, read-only (network engineer review)
    - LLM accessed via OpenRouter/NineRouter (OpenAI-compatible SDK, just swap base_url)

Flow:
    1. Load anomaly data from fact_kpi (latest period)
    2. Retrieve corroborating shift logs via SQLite FTS5 (domain + location filtered)
    3. Compute deterministic confidence score from Z-score + log corroboration count
    4. Call LLM with structured context, instruct JSON output
    5. Parse LLM response; graceful fallback if LLM is unavailable (rate limit etc.)
    6. Attach deterministic confidence before returning — LLM never touches this number

Model selection (for ITASE "alasan pemilihan teknologi" criterion):
    - meta-llama/llama-3.1-70b-instruct via OpenRouter free tier
    - 128k context window: sufficient for multi-entry shift log retrieval
    - Strong instruction-following for structured JSON output format
    - Low latency for interactive RCA queries
    - Fallback: swap LLM_MODEL env var to gpt-4o / claude-3-5-sonnet for the ITASE final demo
"""

